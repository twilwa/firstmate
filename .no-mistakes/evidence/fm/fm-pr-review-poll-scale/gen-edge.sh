#!/usr/bin/env bash
# gen-edge.sh <seed> <casesdir>: one subdir per edge case, each holding the case file(s).
set -eu
seed=$1 root=$2
mk() { mkdir -p "$root/$1/data/pr-review-ledger"; printf "%s" "$1/data/pr-review-ledger"; }
led() { # url-json next-json -> ledger JSON from the real seed
  jq -c --argjson url "$1" --argjson next "$2" '.url = $url | .generations[-1].next_checkpoint_epoch = $next' "$seed"
}
d=$root/$(mk due-and-notdue); led '"https://github.com/o/r/pull/1"' 1500 > "$d/a.json"; led '"https://github.com/o/r/pull/2"' 1700 > "$d/b.json"
d=$root/$(mk malformed); printf '{broken' > "$d/a.json"
d=$root/$(mk empty-file); : > "$d/a.json"
d=$root/$(mk whitespace-only); printf '  \n\n' > "$d/a.json"
d=$root/$(mk symlink); led '"https://github.com/o/r/pull/3"' 1500 > "$d/real.txt"; ln -s "$d/real.txt" "$d/a.json"
d=$root/$(mk dangling-symlink); ln -s "$d/nowhere.json" "$d/a.json"
d=$root/$(mk directory); mkdir "$d/a.json"
d=$root/$(mk fifo); mkfifo "$d/a.json"
d=$root/$(mk nul-byte); { led '"https://github.com/o/r/pull/4"' 1500 | tr -d '\n'; printf '\0\n'; } > "$d/a.json"
d=$root/$(mk nul-inside-string); printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://x/\0y","generations":[{"next_checkpoint_epoch":1500}]}' > "$d/a.json"
d=$root/$(mk escaped-nul-url); led '"https://x/\u0000y"' 1500 > "$d/a.json"
d=$root/$(mk wrong-schema); jq -c '.schema="other"' "$seed" > "$d/a.json"
d=$root/$(mk empty-generations); jq -c '.generations=[]' "$seed" > "$d/a.json"
d=$root/$(mk generations-object); jq -c '.generations={"a":1}' "$seed" > "$d/a.json"
d=$root/$(mk url-number); led '42' 1500 > "$d/a.json"
d=$root/$(mk top-level-array); printf '[1,2]\n' > "$d/a.json"
d=$root/$(mk top-level-string); printf '"x"\n' > "$d/a.json"
d=$root/$(mk top-level-null); printf 'null\n' > "$d/a.json"
d=$root/$(mk next-string-digits); led '"https://github.com/o/r/pull/5"' '"1500"' > "$d/a.json"
d=$root/$(mk next-string-nondigit); led '"https://github.com/o/r/pull/6"' '"15x"' > "$d/a.json"
d=$root/$(mk next-float); led '"https://github.com/o/r/pull/7"' 1500.0 > "$d/a.json"
d=$root/$(mk next-float-frac); led '"https://github.com/o/r/pull/8"' 1500.5 > "$d/a.json"
d=$root/$(mk next-exponent); printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://github.com/o/r/pull/9","generations":[{"next_checkpoint_epoch":1.5e3}]}' > "$d/a.json"
d=$root/$(mk next-big); printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://github.com/o/r/pull/10","generations":[{"next_checkpoint_epoch":100000000000000000000}]}' > "$d/a.json"
d=$root/$(mk next-negative); led '"https://github.com/o/r/pull/11"' -5 > "$d/a.json"
d=$root/$(mk next-null); led '"https://github.com/o/r/pull/12"' null > "$d/a.json"
d=$root/$(mk next-false); led '"https://github.com/o/r/pull/13"' false > "$d/a.json"
d=$root/$(mk next-zero); led '"https://github.com/o/r/pull/14"' 0 > "$d/a.json"
d=$root/$(mk next-array); led '"https://github.com/o/r/pull/15"' '[1]' > "$d/a.json"
d=$root/$(mk next-missing); jq -c '.url="https://github.com/o/r/pull/16" | del(.generations[-1].next_checkpoint_epoch)' "$seed" > "$d/a.json"
d=$root/$(mk last-generation-not-object); printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://github.com/o/r/pull/17","generations":[{"next_checkpoint_epoch":1},5]}' > "$d/a.json"
d=$root/$(mk url-trailing-newlines); led '"https://github.com/o/r/pull/18\n\n"' 1500 > "$d/a.json"
d=$root/$(mk url-inner-newline); led '"https://github.com/o/r/pull/19\nX"' 1500 > "$d/a.json"
d=$root/$(mk url-empty); led '""' 1500 > "$d/a.json"
d=$root/$(mk url-unicode-space); led '"https://github.com/o/r/pull/20 é,x"' 1500 > "$d/a.json"
d=$root/$(mk two-documents); { led '"https://github.com/o/r/pull/21"' 1500; led '"https://github.com/o/r/pull/22"' 1500; } > "$d/a.json"
d=$root/$(mk trailing-garbage); { led '"https://github.com/o/r/pull/23"' 1500 | tr -d '\n'; printf ' garbage'; } > "$d/a.json"
d=$root/$(mk utf8-bom); { printf '\xef\xbb\xbf'; led '"https://github.com/o/r/pull/24"' 1500; } > "$d/a.json"
d=$root/$(mk invalid-utf8-url); printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://x/\xff","generations":[{"next_checkpoint_epoch":1500}]}' > "$d/a.json"
d=$root/$(mk no-trailing-newline); led '"https://github.com/o/r/pull/25"' 1500 | tr -d '\n' > "$d/a.json"
d=$root/$(mk crlf); led '"https://github.com/o/r/pull/26"' 1500 | sed 's/$/\r/' > "$d/a.json"
d=$root/$(mk unreadable); led '"https://github.com/o/r/pull/27"' 1500 > "$d/a.json"; chmod 000 "$d/a.json"
d=$root/$(mk non-json-ext); led '"https://github.com/o/r/pull/28"' 1500 > "$d/a.txt"
d=$root/$(mk hidden-json); led '"https://github.com/o/r/pull/29"' 1500 > "$d/.a.json"
d=$root/$(mk name-with-space); led '"https://github.com/o/r/pull/30"' 1500 > "$d/a b.json"; printf '{bad' > "$d/c d.json"
d=$root/$(mk name-with-newline); printf '{bad' > "$d/$(printf 'a\nb').json"
d=$root/$(mk huge-ledger); jq -c '.url="https://github.com/o/r/pull/31" | .generations = [range(0;3000) as $i | .generations[0]] | .generations[-1].next_checkpoint_epoch=1500' "$seed" > "$d/a.json"
d=$root/$(mk deep-nesting); { printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://github.com/o/r/pull/32","x":'; for i in $(seq 600); do printf '['; done; for i in $(seq 600); do printf ']'; done; printf ',"generations":[{"next_checkpoint_epoch":1500}]}'; } > "$d/a.json"
d=$root/$(mk empty-dir); :
d=$root/$(mk ordering-bad-first); printf '{bad' > "$d/b.json"; printf '{bad' > "$d/a.json"; led '"https://github.com/o/r/pull/33"' 1500 > "$d/c.json"; led '"https://github.com/o/r/pull/34"' 1400 > "$d/0.json"
d=$root/$(mk duplicate-keys); printf '{"schema":"firstmate-pr-review-ledger.v1","url":"https://github.com/o/r/pull/35","url":"https://github.com/o/r/pull/36","generations":[{"next_checkpoint_epoch":1500}]}' > "$d/a.json"
